"""Render committed drill evidence into docs/RESULTS.md and the README summary.

Reads evidence/drills/*/result.json (written by the analyzer, downloaded by
run-drill.sh) - the numbers on the page are only ever what a drill measured.

    python scripts/publish_results.py
"""

from __future__ import annotations

import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "evidence" / "drills"
RESULTS_MD = ROOT / "docs" / "RESULTS.md"
README = ROOT / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

BADGE = {"PASS": "PASS", "FAIL": "**FAIL**", "INCONCLUSIVE": "INCONCLUSIVE"}


def load():
    runs = []
    for path in sorted(EVIDENCE.glob("*/result.json")):
        r = json.loads(path.read_text())
        r["_dir"] = path.parent.relative_to(ROOT).as_posix()
        runs.append(r)
    return sorted(runs, key=lambda r: r.get("drill_started_at") or r["run_id"], reverse=True)


def fmt(v, unit="s"):
    return "-" if v is None else f"{v:.1f} {unit}"


def store(r, name, key):
    v = (r.get("rpo_by_store") or {}).get(name, {}).get(key)
    if key == "rpo_seconds":
        return fmt(v)
    return "-" if v is None else str(v)


def pct(values, q):
    values = sorted(values)
    if not values:
        return None
    if len(values) == 1:
        return values[0]
    return statistics.quantiles(values, n=100, method="inclusive")[q - 1]


def summary(runs):
    graded = [r for r in runs if r["verdict"] in ("PASS", "FAIL")]
    rtos = [r["rto_seconds"] for r in graded if r.get("rto_seconds") is not None]
    rpos = [r["rpo_seconds"] for r in graded if r.get("rpo_seconds") is not None]
    passed = sum(1 for r in graded if r["verdict"] == "PASS")
    return {
        "drills": len(runs),
        "graded": len(graded),
        "passed": passed,
        "rto_p50": pct(rtos, 50),
        "rto_p90": pct(rtos, 90),
        "rto_max": max(rtos) if rtos else None,
        "rpo_max": max(rpos) if rpos else None,
    }


def results_page(runs, s):
    lines = [
        "# Measured DR drill results",
        "",
        "Generated by `scripts/publish_results.py` from `evidence/drills/*/result.json`.",
        "Every row is one automated region-impairment drill; raw per-second probe",
        "samples sit next to each result so any number here can be recomputed.",
        "",
        f"**{s['passed']}/{s['graded']} graded drills passed** - "
        f"RTO p50 {fmt(s['rto_p50'])}, p90 {fmt(s['rto_p90'])}, worst {fmt(s['rto_max'])}; "
        f"worst RPO {fmt(s['rpo_max'])}.",
        "",
        "| Drill | Verdict | RTO | Detect | DB promote | Verify | DNS + client | RPO Aurora | RPO DynamoDB | Lost writes (A/D) | Evidence |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        ph = r.get("phases") or {}
        lines.append(
            f"| {r['run_id']} | {BADGE.get(r['verdict'], r['verdict'])} | {fmt(r.get('rto_seconds'))} "
            f"| {fmt(ph.get('detection'))} | {fmt(ph.get('db_promotion'))} | {fmt(ph.get('dr_verification'))} "
            f"| {fmt(ph.get('dns_and_client'))} | {store(r, 'aurora', 'rpo_seconds')} | {store(r, 'dynamodb', 'rpo_seconds')} "
            f"| {store(r, 'aurora', 'lost_writes')}/{store(r, 'dynamodb', 'lost_writes')} "
            f"| [result](../{r['_dir']}/result.json) |"
        )
    failing = [r for r in runs if r.get("reasons")]
    if failing:
        lines += ["", "## Why drills did not pass", ""]
        for r in failing:
            for reason in r["reasons"]:
                lines.append(f"- `{r['run_id']}`: {reason}")
    lines += [
        "",
        "## How to read this",
        "",
        "- **RTO** is client-observed: first failed write to first acknowledged write after recovery, at 1 s resolution.",
        "- **Detect** = watchdog decision - first client error. **DB promote** = `FailoverGlobalCluster` issued - DR cluster is writer.",
        "- **Verify** = promoted - DR `/health` confirmed from outside. **DNS + client** = verified - client actually served by DR.",
        "- **RPO** = largest window of acknowledged writes missing after failover (0 = nothing the client was told was saved was lost).",
        "- Targets and the fault injected are recorded inside each `result.json`.",
        "",
    ]
    return "\n".join(lines)


def readme_block(runs, s):
    if not runs:
        return f"{START}\n_No drills have been published yet - run the `dr-drill` workflow._\n{END}"
    latest = runs[0]
    return "\n".join([
        START,
        f"| Latest drill | Verdict | Measured RTO | Measured RPO | Target RTO / RPO |",
        "|---|---|---|---|---|",
        f"| `{latest['run_id']}` | {BADGE.get(latest['verdict'], latest['verdict'])} | {fmt(latest.get('rto_seconds'))} "
        f"| {fmt(latest.get('rpo_seconds'))} | {latest['targets']['rto_seconds']:.0f} s / {latest['targets']['rpo_seconds']:.0f} s |",
        "",
        f"Across **{s['drills']}** drills: {s['passed']}/{s['graded']} passed, RTO p50 {fmt(s['rto_p50'])} / "
        f"worst {fmt(s['rto_max'])}, worst RPO {fmt(s['rpo_max'])}. Full history: [docs/RESULTS.md](docs/RESULTS.md).",
        END,
    ])


def main():
    runs = load()
    s = summary(runs)
    RESULTS_MD.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_MD.write_text(results_page(runs, s) if runs else "# Measured DR drill results\n\nNo drills yet.\n", encoding="utf-8")

    readme = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(readme):
        raise SystemExit(f"README.md is missing the {START} ... {END} markers")
    README.write_text(pattern.sub(lambda _: readme_block(runs, s), readme), encoding="utf-8")
    print(f"published {len(runs)} drill(s)")


if __name__ == "__main__":
    main()
